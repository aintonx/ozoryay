"use client";

import type { Observer } from "@/lib/sky/realsky";

/**
 * Откуда смотрят на небо — всегда её город из настроек.
 *
 * Здесь был запрос геолокации: небо ехало бы за ней, если бы она разрешила
 * браузеру сообщить, где находится. Убрано намеренно. Подарок не должен
 * начинаться с окна «сайт запрашивает ваше местоположение» — это пугает, а
 * взамен не даёт ничего: на тысяче километров разницы созвездия над головой
 * почти те же, и заметить подмену невозможно.
 *
 * Функция оставлена, чтобы место наблюдателя по-прежнему приходило в небо
 * одним путём: понадобится — сюда вернётся выбор города, а не браузерный
 * запрос.
 */
export function useObserver(where: Observer): Observer {
  return where;
}
