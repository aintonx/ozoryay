/**
 * Точки на карте: места, которые для нас двоих что-то значат.
 *
 * Тот же принцип, что у MEMORIES и LETTERS: обычный список в коде, без базы
 * и без админки. Добавить новое место — значит дописать сюда один объект
 * и, если есть, положить фото в public/memories.
 *
 * Ниже — три примера для проверки, что карта и карточки работают. Замени
 * координаты, даты и тексты на настоящие, когда будешь готов; саму
 * структуру трогать не обязательно.
 */

/**
 * Тип события определяет только подпись на карточке — форма и цвет метки
 * на карте одни и те же для всех типов. Второго тона в палитре сайта нет
 * (см. globals.css, «шесть значений, больше ни одного тона»), поэтому
 * различие по типу — текстовое, а не цветовое.
 */
export type PlaceKind = "milestone" | "lived" | "venue" | "trip";

export const PLACE_KIND_LABEL: Record<PlaceKind, string> = {
  milestone: "Важный момент",
  lived: "Жили здесь",
  venue: "Заведение",
  trip: "Поездка",
};

export interface Place {
  /** Свой у каждой точки — по нему React отличает маркеры и карточки. */
  id: string;
  /** Тип события: определяет подпись на карточке. */
  kind: PlaceKind;
  /** Заголовок карточки. */
  title: string;
  /** Широта. */
  lat: number;
  /** Долгота. */
  lon: number;
  /** Когда это было. Не обязательно точная дата — подходит и «сентябрь 2025». */
  date?: string;
  /** Текст карточки. */
  description?: string;
  /**
   * Путь к фото, например "/memories/memory-04.jpg" — файл должен лежать
   * в public/. Необязательно: без фото карточка просто короче.
   */
  photo?: string;
}

