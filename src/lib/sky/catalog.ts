/**
 * Каталог настоящих звёзд. Координаты — эпоха J2000, как в астрономических
 * справочниках: прямое восхождение и склонение в градусах, звёздная величина
 * (чем меньше, тем ярче: у Сириуса −1.46, глаз видит примерно до 6).
 *
 * Здесь только то, что реально видно из средних широт невооружённым глазом —
 * созвездия, которые она узнает, выйдя на улицу. Файл статический: никаких
 * запросов наружу, всё считается в браузере.
 */

export interface CatalogStar {
  /** Прямое восхождение, градусы. */
  ra: number;
  /** Склонение, градусы. */
  dec: number;
  /** Видимая звёздная величина. */
  mag: number;
  /** Собственное имя — только у тех, у кого оно на слуху. */
  name?: string;
}

export interface Constellation {
  /** Русское название — его увидит она. */
  name: string;
  /** Звёзды созвездия. */
  stars: CatalogStar[];
  /** Линии рисунка: пары индексов в `stars`. */
  lines: Array<[number, number]>;
}

