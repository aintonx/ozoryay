/**
 * Детерминированная случайность.
 *
 * Всё небо обязано быть воспроизводимым: звезда №57 всегда в одной точке,
 * между визитами небо не перетасовывается, оно только растёт.
 */

/** mulberry32 — быстрый PRNG с полным периодом на 32 битах. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Последовательность R2 — квазислучайная, с низким расхождением.
 *
 * Чистый Math.random() сбивает звёзды в комки и оставляет проплешины: небо
 * выглядит как рассыпанная соль. R2 раскладывает точки почти равномерно, но
 * без следа решётки — именно так, как выглядит настоящее звёздное поле.
 * Дальше сверху накладывается мелкое дрожание от mulberry32, иначе
 * равномерность становится слишком заметной.
 *
 * Основана на пластическом числе: корне уравнения x³ = x + 1.
 */
const PLASTIC = 1.324717957244746;
const A1 = 1 / PLASTIC;
const A2 = 1 / (PLASTIC * PLASTIC);

export function r2(n: number): [number, number] {
  return [(0.5 + A1 * n) % 1, (0.5 + A2 * n) % 1];
}
