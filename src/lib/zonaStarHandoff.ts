/**
 * Передача «звезда ещё горит» со страницы `/zona` на главный экран.
 *
 * `/zona` и `/` — две разные страницы с двумя разными канвасами: звезда
 * на втором рождается с нуля, и если ничего не передать, свет, который
 * только что горел в полную силу, обрывается за один кадр на стыке
 * переходов. Здесь передаётся одно-единственное «уходили при горящей
 * звезде» — главный экран стартует с полной яркости и гасит её сам,
 * плавно, пока виджеты возвращаются на место.
 *
 * Переменная модуля, а не `sessionStorage`: читать её нужно в самом
 * первом рендере `Night` (канвас создаётся с тем, что в этот момент
 * в пропсах), а читать хранилище браузера при рендере нельзя — на
 * статическом экспорте это расхождение с серверной разметкой. Модуль
 * живёт, пока живёт вкладка, а на жёсткой перезагрузке честно обнуляется:
 * гаснуть там уже нечему.
 */
let lit = false;

/** Вызывается страницей «Зоны», когда она уходит с горящей звездой. */
export function markZonaStarLit(): void {
  lit = true;
}

/** Только читает. Рендер может случиться дважды (StrictMode), поэтому
 *  сбрасывать здесь нельзя — см. `clearZonaStarLit`. */
export function peekZonaStarLit(): boolean {
  return lit;
}

/** Сбрасывается из эффекта, когда звезду уже принял главный экран. */
export function clearZonaStarLit(): void {
  lit = false;
}
