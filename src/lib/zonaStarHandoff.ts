/**
 * Передача состояния со страницы `/zona` на главный экран.
 *
 * `/zona` и `/` — две разные страницы с двумя разными канвасами. Всё, что
 * на стыке должно остаться непрерывным, главной приходится узнавать самой,
 * и узнавать в самом первом рендере: канвас создаётся с теми пропсами,
 * которые есть в этот момент, и поправить их задним числом уже нельзя —
 * первые кадры будут нарисованы не так.
 *
 * Передаётся два факта:
 *
 *  - `starLevel` — насколько ярко горела звезда «Зоны», когда уходили.
 *    После закрытия жестом это ~0 (звезда погасла вместе с картой — см.
 *    `zonaStarTrackMs`), и главная стартует с нуля, ничего не добавляя.
 *    После ухода иным способом (жест «назад») там ещё 1, и главная гасит
 *    её сама, плавно;
 *
 *  - `returning` — вернулись жестом закрытия, а не пришли «с нуля».
 *    Без этого первый рендер главной — это «вступление идёт»
 *    (`intro === 0`), канвас создаётся с `dawn: true`, и на возврате
 *    на долю секунды вспыхивает зарево рассвета, которое потом гаснет
 *    420 мс — ровно под выезжающими виджетами. Раньше об этом сообщала
 *    только метка в `sessionStorage`, но её нельзя читать при рендере
 *    (на статическом экспорте это расхождение с серверной разметкой),
 *    и читалась она уже после первого рендера.
 *
 * Переменная модуля: живёт, пока живёт вкладка, а на жёсткой перезагрузке
 * честно обнуляется — гаснуть и возвращаться там нечему.
 */
export interface ZonaExit {
  starLevel: number;
  returning: boolean;
}

let exit: ZonaExit | null = null;

/**
 * Вызывается страницей «Зоны» при уходе. Можно звать несколько раз за
 * один уход (закрытие жестом и размонтирование): `returning` один раз
 * поднятый не опускается, а `starLevel` берётся последний.
 */
export function markZonaExit(next: ZonaExit): void {
  exit = { starLevel: next.starLevel, returning: next.returning || (exit?.returning ?? false) };
}

/** Только читает. Рендер может случиться дважды (StrictMode), поэтому
 *  сбрасывать здесь нельзя — см. `clearZonaExit`. */
export function peekZonaExit(): ZonaExit | null {
  return exit;
}

/** Сбрасывается из эффекта, когда главный экран уже всё принял. */
export function clearZonaExit(): void {
  exit = null;
}
