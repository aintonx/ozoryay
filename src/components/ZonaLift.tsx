"use client";

import { useEffect, useRef, type ReactNode } from "react";

interface ZonaLiftProps {
  /** Пошёл подъём взгляда: виджеты уже уезжают вместе с остальными (см.
   *  `veiled` в `Night`), а само небо приближается вслед за ними. */
  active: boolean;
  /** Небо целиком — оно оборачивается здесь, а не подменяется: тот же
   *  канвас, та же картинка звёзд, без искажений и без второго рендера. */
  children: ReactNode;
  /** Взгляд поднят до конца, тьма сомкнулась — можно открывать страницу. */
  onDone: () => void;
}

/** От первого кадра до вызова onDone. */
const LIFT_MS = 1500;

/**
 * Насколько увеличивается небо. Не подбор на глаз, а счёт от реальной
 * геометрии: `LAYOUT.groundY` в `lib/sky/layout.ts` — 0.862 (линия земли
 * как доля высоты экрана), а самый высокий холм поднимается над ней ещё
 * на 0.073, то есть его пик — на 0.789. Увеличение в 1/0.789 ≈ 1.27 увело
 * бы пик ровно на нижний край экрана; 1.4 — уводит его за край с явным
 * запасом. Якорь растяжения — верхняя кромка (`transformOrigin`), поэтому
 * растёт вниз ровно то, что и должно уйти за нижний край, а не картинка
 * целиком в обе стороны от середины.
 */
const ZOOM = 1.4;

/**
 * Подъём взгляда к «Зоне».
 *
 * Раньше здесь был поворот в 3D (`perspective` + `rotateX`) — но плоский
 * канвас неба под таким углом не поворачивается как купол, а плющится и
 * плывёт, потому что это одна и та же плоская картинка, снятая под углом,
 * а не настоящая сцена с глубиной. Читалось не как «запрокинул голову»,
 * а как «экран сломался».
 *
 * Здесь то же самое ощущение получено куда более честным способом: чистое
 * увеличение от верхней кромки. Звёзды не искажаются — угол между любыми
 * двумя из них тот же, что и был, меняется только масштаб, — а линия
 * земли и холмы у горизонта (они всегда внизу, см. `LAYOUT.groundY`)
 * растут вместе с картинкой и в какой-то момент целиком уезжают за нижний
 * край. Именно это и происходит, когда запрокидываешь голову: горизонт
 * пропадает из виду, а небо остаётся собой, просто другая его часть
 * заполняет собой весь взгляд.
 *
 * Симметрично работает и в обратную сторону: когда `active` становится
 * `false` (в том числе при возврате со страницы `/zona` — см. `Night`),
 * тот же переход разворачивается назад, тем же путём и с той же
 * длительностью. Отдельной анимации возврата поэтому не заводим.
 */
export default function ZonaLift({ active, children, onDone }: ZonaLiftProps) {
  const fired = useRef(false);

  useEffect(() => {
    if (!active) {
      fired.current = false;
      return;
    }
    if (fired.current) return;
    fired.current = true;
    const t = window.setTimeout(onDone, LIFT_MS);
    return () => window.clearTimeout(t);
  }, [active, onDone]);

  return (
    <div className="fixed inset-0 overflow-hidden">
      <div
        className="fixed inset-0"
        style={{
          transform: active ? `scale(${ZOOM})` : "scale(1)",
          transformOrigin: "50% 0%",
          transition: `transform ${LIFT_MS}ms var(--ease-lift)`,
          willChange: "transform",
        }}
      >
        {children}
      </div>

      {/* Тьма по краям: смыкается ровно к моменту, когда взгляд поднят
          до конца, и прячет под собой переход на следующую страницу — а при
          возврате точно так же расходится обратно. */}
      <div
        aria-hidden
        className="pointer-events-none fixed inset-0 z-40"
        style={{
          background: "radial-gradient(circle at 50% 50%, transparent 0%, var(--color-night-deep) 85%)",
          opacity: active ? 1 : 0,
          transition: `opacity ${LIFT_MS}ms var(--ease-lift)`,
        }}
      />
    </div>
  );
}
