"use client";

import { useEffect, useRef, type ReactNode } from "react";

/**
 * Насколько увеличивается небо в полностью поднятом состоянии. Не подбор
 * на глаз, а счёт от реальной геометрии: `LAYOUT.groundY` в
 * `lib/sky/layout.ts` — 0.862 (линия земли как доля высоты экрана), а самый
 * высокий холм поднимается над ней ещё на 0.073, то есть его пик — на
 * 0.789. Увеличение в 1/0.789 ≈ 1.27 увело бы пик ровно на нижний край
 * экрана; 1.4 — уводит его за край с явным запасом. Якорь растяжения —
 * верхняя кромка (`transformOrigin` в `LiftedSky` ниже), поэтому растёт
 * вниз ровно то, что и должно уйти за нижний край, а не картинка целиком
 * в обе стороны от середины.
 */
export const ZONA_LIFT_ZOOM = 1.4;

/** От первого кадра до вызова onDone — обычный подъём, тапом по виджету. */
export const ZONA_LIFT_MS = 1500;

/**
 * То же самое, но при включённом `prefers-reduced-motion`: сцена вообще не
 * масштабируется (см. `LiftedSky` ниже — `reducedMotion` держит `scale(1)`
 * постоянно), поэтому полутора секунд наклона головы здесь просто нечему
 * заполнить. Остаётся короткая метка «сейчас откроется следующее» — тьма
 * по краям всё равно вспыхивает и гаснет, но кратко, как и полагается
 * кросс-фейду вместо параллакса.
 */
export const ZONA_LIFT_REDUCED_MS = 260;

interface LiftedSkyProps {
  /** 0 — небо в покое, как на главном экране; 1 — полностью поднято,
   *  горизонт и холмы ушли за нижний край. Дробные значения — небо
   *  где-то между: то самое, что нужно жесту `usePullToClose` на
   *  странице `/zona`, чтобы тянуть камеру вниз пальцем 1:1, а не только
   *  карточку поверх статичной картинки. */
  t: number;
  /** Готовая CSS-строка `transition`. Вызывающий код сам решает, ехать ли
   *  плавно (обычный тап-подъём или отпущенный жест) или вовсе без
   *  перехода (сам жест пальца — движение обязано поспевать за пальцем
   *  день в день, а не по кривой, см. apple-design: «direct manipulation»). */
  transition: string;
  reducedMotion: boolean;
  children: ReactNode;
}

/**
 * Небо, обёрнутое в подъём взгляда, — общая визуальная часть для обоих
 * направлений жеста.
 *
 * Раньше здесь был поворот в 3D (`perspective` + `rotateX`) — но плоский
 * канвас неба под таким углом не поворачивается как купол, а плющится и
 * плывёт, потому что это одна и та же плоская картинка, снятая под углом,
 * а не настоящая сцена с глубиной. Читалось не как «запрокинул голову»,
 * а как «экран сломался».
 *
 * Здесь то же самое ощущение получено куда более честным способом: чистое
 * увеличение от верхней кромки. Звёзды не искажаются — угол между любыми
 * двумя из них тот же, что и был, меняется только масштаб, — а линия
 * земли и холмы у горизонта растут вместе с картинкой и в какой-то момент
 * целиком уезжают за нижний край. Именно это и происходит, когда
 * запрокидываешь голову: горизонт пропадает из виду, а небо остаётся
 * собой, просто другая его часть заполняет собой весь взгляд.
 *
 * Используется дважды одним и тем же способом: `ZonaLift` ниже управляет
 * `t` дискретно (0 или 1, тапом по виджету), а страница `/zona` — жестом
 * пальца, непрерывно, потому и вынесено в отдельный, не привязанный
 * к таймеру компонент. Открытие и закрытие обязаны читаться как один
 * и тот же приём туда-обратно, а не как два разных.
 */
export function LiftedSky({ t, transition, reducedMotion, children }: LiftedSkyProps) {
  // При `prefers-reduced-motion` сцена не должна плыть фоном во весь экран
  // (apple-design: «avoid full-viewport moving backgrounds» — здесь именно
  // такой случай, только через scale, а не через сдвиг). Масштаб держится
  // на 1 всегда; тьма по краям — единственное, что ещё меняется, и она же
  // остаётся кросс-фейдом, который эту смену состояний обозначает.
  const scale = reducedMotion ? 1 : 1 + (ZONA_LIFT_ZOOM - 1) * t;

  return (
    <div className="fixed inset-0 overflow-hidden">
      <div
        className="fixed inset-0"
        style={{
          transform: `scale(${scale})`,
          transformOrigin: "50% 0%",
          transition,
          willChange: "transform",
        }}
      >
        {children}
      </div>

      {/* Тьма по краям: смыкается ровно к моменту, когда взгляд поднят до
          конца, и прячет под собой переход на следующий экран — а при
          возврате точно так же расходится обратно, в том же темпе, что
          и сама сцена (одна и та же `transition` на обоих узлах). */}
      <div
        aria-hidden
        className="pointer-events-none fixed inset-0 z-40"
        style={{
          background: "radial-gradient(circle at 50% 50%, transparent 0%, var(--color-night-deep) 85%)",
          opacity: t,
          transition,
        }}
      />
    </div>
  );
}

interface ZonaLiftProps {
  /** Пошёл подъём взгляда: виджеты уже уезжают вместе с остальными (см.
   *  `veiled` в `Night`), а само небо приближается вслед за ними. */
  active: boolean;
  reducedMotion: boolean;
  /** Небо целиком — оно оборачивается здесь, а не подменяется: тот же
   *  канвас, та же картинка звёзд, без искажений и без второго рендера. */
  children: ReactNode;
  /** Взгляд поднят до конца, тьма сомкнулась — можно открывать страницу. */
  onDone: () => void;
}

/**
 * Подъём взгляда к «Зоне» тапом по виджету (см. `onOpenZona` в `Night`).
 *
 * Обратный путь — жест пальца на самой странице `/zona` — здесь не живёт:
 * он тянет `LiftedSky` напрямую (см. `usePullToClose` и сборку `t` там),
 * потому что жесту нужно значение, а не булев флаг с таймером. К моменту,
 * когда возврат долистан до конца и страница уходит на `/`, небо уже
 * опущено самим жестом — этот компонент на обратном пути ничего не
 * переигрывает, только держит `active=false`, то есть плоский `scale(1)`
 * без какого-либо перехода (см. `Night`, ветка `zonaReturning`).
 */
export default function ZonaLift({ active, reducedMotion, children, onDone }: ZonaLiftProps) {
  const fired = useRef(false);
  const ms = reducedMotion ? ZONA_LIFT_REDUCED_MS : ZONA_LIFT_MS;

  useEffect(() => {
    if (!active) {
      fired.current = false;
      return;
    }
    if (fired.current) return;
    fired.current = true;
    const t = window.setTimeout(onDone, ms);
    return () => window.clearTimeout(t);
  }, [active, onDone, ms]);

  return (
    <LiftedSky
      t={active ? 1 : 0}
      reducedMotion={reducedMotion}
      transition={`transform ${ms}ms var(--ease-lift), opacity ${ms}ms var(--ease-lift)`}
    >
      {children}
    </LiftedSky>
  );
}
