/** Общая обёртка квадрата: одно и то же стекло, один и тот же угол —
 *  что под настоящим рисунком «Зоны», что под размытым силуэтом рядом.
 *  Три иконки обязаны читаться как один и тот же язык, а не как
 *  «одна настоящая плюс две другие». */
function IconFrame({ children, tiltRef }: { children: ReactNode; tiltRef?: Ref<HTMLDivElement> }) {
  return (
    <div ref={tiltRef} className={`glass ${ICON} ${SQUIRCLE} ${tiltRef ? "tilt" : ""}`}>
      {children}
    </div>
  );
}

/** Иконка «Зоны» — единственная из трёх кликабельная: тап поднимает
 *  взгляд к небу и открывает страницу входа (см. `onOpenZona`/`ZonaLift`
 *  в `Night`). Наклон вслед за курсором — только у самого квадрата, не
 *  у подписи под ним: подпись остаётся на месте и не косит вместе с
 *  иконкой в 3D, иначе мелкий текст в наклоне на бегу нечитаем.
 */
function ZonaIcon({ onOpen }: { onOpen: () => void }) {
  const tiltRef = useTilt(true);

  return (
    <button
      type="button"
      onClick={(e) => {
        // Тот же приём, что и у остальных карточек-кнопок сайта (см.
        // `WidgetButton`): убираем фокус после касания, чтобы кольцо
        // фокуса не оставалось висеть на стекле. Клавиатурный вызов
        // (`e.detail === 0`) фокус сохраняет.
        if (e.detail > 0) e.currentTarget.blur();
        onOpen();
      }}
      className="flex flex-col items-center gap-[0.4rem]"
    >
      <IconFrame tiltRef={tiltRef as Ref<HTMLDivElement>}>
        <ZonaMark />
      </IconFrame>
      <span className="font-system text-[12px] leading-none text-star/80">Зона</span>
    </button>
  );
}

/**
 * Один из двух «ещё не открытых» соседей «Зоны» — той же формы и того же
 * стекла, но не кнопка: за размытием пока в самом деле ничего нет, и
 * притворяться, что там уже есть куда нажать, было бы ровно той нечестной
 * витриной, от которой сайт как раз отказался (см. прежний комментарий
 * этого файла про «Откроется позже»). Наклона вслед за курсором тоже
 * нет — он был бы отдельным намёком на интерактивность, которой здесь нет.
 */
function LockedIcon({ warm }: { warm: boolean }) {
  return (
    <div className="flex flex-col items-center gap-[0.4rem]">
      <IconFrame>
        <BlurredMark warm={warm} />
        <div className="absolute inset-0 flex items-center justify-center">
          <LockGlyph />
        </div>
      </IconFrame>
      <span className="font-system text-[12px] leading-none text-star/50">?</span>
    </div>
  );
}

/**
 * Домашний экран телефона: место одного полноширинного виджета «Зоны»
 * теперь занимает строка из трёх иконок приложений, в стиле iOS —
 * органичнее виджета и легче для экрана, на котором и без того много
 * карточек (прямой запрос). Позиции всех остальных виджетов в сетке не
 * меняются: этот компонент по-прежнему один `col-span-2`-элемент в самом
 * низу сетки (см. `HomeScreen`), просто его содержимое — не карточка,
 * а ряд иконок.
 *
 * `max-w-[18rem] mx-auto`: без этого на широком экране (desktop) три
 * фиксированного размера иконки разъехались бы по всей ширине сетки
 * (до 44rem) с непомерно широкими промежутками между ними — тесная
 * строка вместо неё держит то же расстояние между иконками, что и на
 * телефоне, независимо от того, насколько широк сам блок виджетов.
 */
export default function ZonaWidget({ onOpen, className = "" }: ZonaWidgetProps) {
  return (
    <div className={`mx-auto flex w-full max-w-[18rem] items-start justify-between ${className}`}>
      <LockedIcon warm />
      <ZonaIcon onOpen={onOpen} />
      <LockedIcon warm={false} />
    </div>
  );
}
