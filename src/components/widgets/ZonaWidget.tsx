/** Одна и та же сторона для всех трёх иконок — то, что раньше было одним
 *  виджетом высотой `8rem`, теперь строка из трёх квадратов поменьше:
 *  дом виджетов и так был перегружен (прямой запрос — разгрузить), а
 *  сама иконка не обязана быть той же высоты, что карточка, которую она
 *  заменяет. */
const ICON = "h-[4.4rem] w-[4.4rem] shrink-0 overflow-hidden";

