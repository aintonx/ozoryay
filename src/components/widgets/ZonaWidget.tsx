/**
 * Вход в «Зону».
 *
 * Тот же корпус (`glass`, `glass-deep`, `tilt`), что и у остальных карточек
 * сайта, но кнопка, а не витрина: тап поднимает взгляд к небу и открывает
 * страницу входа (см. `onOpenZona`/`ZonaLift` в `Night`). За самой дверью
 * пока предпросмотр без базы — `/zona` честно говорит об этом сама
 * («совсем скоро — как только подключим базу…»), поэтому здесь не нужно
 * притворяться больше, чем есть на самом деле.
 *
 * Раскладка — по образцу кнопок экрана неба (см. `SkyScreen.tsx`, `row`
 * в `WidgetButton`): иконка слева, текст справа, один ряд вместо прежней
 * шапки-заголовка отдельно от содержимого. Разница только в размере самой
 * иконки — там она одна из четырёх на своей кнопке, здесь она одна на всю
 * карточку целиком, которая когда-нибудь станет основой сайта, и ей
 * положено читаться соразмерно этому, а не как ещё один мелкий значок
 * (см. `ZonaIcon` выше).
 *
 * Жирное «ЗОНА» в шапке и приглушённые полосы вместо текста — сняты:
 * вместо места-держателя теперь настоящая строка, а у карточки больше нет
 * отдельной подписи-названия — маяк сам себе имя. Строка под ней — по-прежнему
 * подсказка, а не смысл, тем же шрифтом/размером/цветом (`text-[15px]`,
 * `text-star/60`), что и у «он улетит ко мне» под «Отправить поцелуй»
 * (`WidgetButton`, layout=tile): «нажми, чтобы открыть» стало «нажми,
 * чтобы светить» — тоже про действие по тапу, только теперь про свет,
 * а не про открытие двери.
 *
 * `min-h-[8rem]` — тот же пол, что стоял и раньше. Новое содержимое
 * (иконка + фраза + подсказка, в один ряд) по прикидке через похожий
 * по метрике шрифт садится примерно в 7.2–7.4rem вместе с падингом —
 * без права на промах, но внутри пола, не поверх него. Живого браузера
 * под рукой не было, так что это счёт, а не измерение: если системный
 * шрифт даст перенос на строку больше, `min-h` не помешает карточке
 * подрасти — `HomeScreen` сам пересчитывает масштаб всей сетки по факту
 * (`fit()`), а не наоборот, так что лишняя строка ужмёт сетку, а не
 * обрежет карточку.
 */
export default function ZonaWidget({ onOpen, className = "" }: ZonaWidgetProps) {
  const tiltRef = useTilt(true, TILT_MAX_DEG_DEEP / TILT_MAX_DEG);

  return (
    <button
      ref={tiltRef as Ref<HTMLButtonElement>}
      type="button"
      onClick={(e) => {
        // После касания снимаем фокус — как и у остальных карточек-кнопок
        // сайта (см. `WidgetButton`): иначе на стекле остаётся кольцо
        // фокуса, которое здесь читается как рамка интерфейса, а не как
        // часть карточки. Клавиатурный вызов (`e.detail === 0`) фокус
        // сохраняет.
        if (e.detail > 0) e.currentTarget.blur();
        onOpen();
      }}
      className={`glass glass-deep tilt flex min-h-[8rem] w-full min-w-0 items-center gap-[0.9rem] rounded-[1.55rem] p-[0.9rem] text-left ${className}`}
    >
      <ZonaIcon />

      <div className="min-w-0 flex-1">
        <p className="font-system text-[15px] leading-snug text-star/90">
          Зона — маяк на случай конца света: даже если весь мир вокруг однажды
          замолчит
        </p>
        {/*
          Тот же шрифт и то же исполнение, что у подписи «он улетит ко мне»
          под «Отправить поцелуй» (`hint` в `WidgetButton`, layout=tile) —
          полностью, включая цвет (`text-star/60`) и размер: если тот
          вырастет, этот растёт вместе с ним. Отступ сверху (`0.28em`) —
          тот же, которым `WidgetButton` везде отделяет свой `hint` от
          `label` — здесь ровно та же пара, просто без общего компонента.
        */}
        <span className="font-system mt-[0.28em] block text-[15px] leading-snug text-star/60">
          нажми, чтобы светить
        </span>
      </div>
    </button>
  );
}
