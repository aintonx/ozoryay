"use client";

import { IconChevronUp } from "./Icons";

/**
 * Единый размер стрелки-подсказки о свайпе — что здесь, что в заставке
 * (`TitleDawn`), где рядом с ней остаётся подпись. Раньше в разных местах
 * стояли то 13, то 14 пикселей — на глаз почти одно и то же, но не совсем;
 * теперь это одно число на весь сайт.
 *
 * Это ширина в пикселях, не сторона квадрата: у формы `IconChevronUp`
 * фиксированное соотношение 4:1, высота считается от ширины сама (см.
 * комментарий у неё). Число 44 — не с потолка, а прямой промер ширины
 * стрелки Reachability на реальном скриншоте iOS: там же и там же взято
 * соотношение сторон и толщина штриха самой иконки.
 */
export const SWIPE_HINT_ARROW_SIZE = 44;

interface SwipeHintArrowProps {
  /** Куда указывает и куда зовёт свайпнуть: вверх — к небу, вниз — обратно к виджетам. */
  direction: "up" | "down";
  onClick: () => void;
  className?: string;
}

/**
 * Голая стрелка-подсказка, без подписи рядом — только для главного экрана
 * и экрана неба (см. `HomeScreen`/`SkyScreen`). Раньше здесь стоял текст
 * («смахни вверх» / «смахни вниз»); теперь вместо слов — сама стрелка,
 * как это принято на дорогих сайтах: не объявление, а намёк. Подпись рядом
 * со стрелкой остаётся во всех остальных местах сайта (заставка, зажжённый
 * контент, путешествие к созвездию) — этот компонент их не трогает и не
 * заменяет.
 *
 * Стрелка стоит неподвижно — раньше она тихо дышала и покачивалась
 * (`hint-breathe-up`/`hint-breathe-down` в globals.css), анимация снята
 * по прямому запросу вместе с заменой формы на `IconChevronUp`. У стрелки
 * «вниз» направление по-прежнему держится поворотом на 180° — просто
 * теперь он статичный (`.swipe-hint-arrow--down svg` в globals.css), а не
 * часть анимации, которая эту стрелку заодно и покачивала.
 *
 * Отступ вокруг иконки (`p-[0.55rem]`) — это зона нажатия, не сама
 * стрелка: без него попасть пальцем было бы неудобно. Больше — уже
 * раздувало высоту, которую резервирует под себя эта строка внизу
 * главного экрана: `HomeScreen` меряет, сколько места осталось сетке
 * виджетов, уже за вычетом этой строки, и слишком щедрый отступ здесь
 * заметно ужимал сетку выше. Если снова понадобится увеличить зону
 * нажатия — делать это с оглядкой на `fit()` в `HomeScreen`, не просто
 * прибавляя падинг.
 */
export function SwipeHintArrow({ direction, onClick, className = "" }: SwipeHintArrowProps) {
  return (
    <button
      type="button"
      onClick={(e) => {
        if (e.detail > 0) e.currentTarget.blur();
        onClick();
      }}
      aria-label={direction === "up" ? "Смахнуть вверх, к небу" : "Смахнуть вниз, к виджетам"}
      className={`swipe-hint-arrow swipe-hint-arrow--${direction} z-[1] mx-auto flex shrink-0 items-center justify-center p-[0.55rem] text-star transition-opacity duration-300 hover:opacity-80 ${className}`}
    >
      <IconChevronUp size={SWIPE_HINT_ARROW_SIZE} />
    </button>
  );
}
